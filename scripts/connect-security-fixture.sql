-- Isolated CI database only. Never use on Supabase production.
create role anon nologin;
create role authenticated nologin;
create schema auth;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),'')::jsonb,'{}'::jsonb) $$;
grant usage on schema auth to anon,authenticated;
grant execute on function auth.uid(),auth.jwt() to anon,authenticated;
create table public.voltara_households(id uuid primary key);
create table public.voltara_members(household_id uuid references public.voltara_households,user_id uuid references auth.users,primary key(household_id,user_id));
alter table public.voltara_members enable row level security;
grant select on public.voltara_members to authenticated;
create policy own_member on public.voltara_members for select to authenticated using(user_id=auth.uid());
create schema storage;
create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
create table storage.objects(id uuid default gen_random_uuid() primary key,bucket_id text references storage.buckets,name text,unique(bucket_id,name));
alter table storage.objects enable row level security;
grant usage on schema storage to authenticated,anon;
grant select,insert on storage.objects to authenticated;
create publication supabase_realtime;
